import streamlit as st
import pandas as pd
from src.utils.metrics import calculate_pareto, calculate_bcg_matrix
from src.components.ui import (
    render_section_header,
    render_insight_box,
    format_currency
)
from src.components.charts import (
    plot_bcg_quadrant_matrix,
    plot_pareto_chart,
    plot_subcategory_margin_bar
)


def render_product_intelligence_view(df: pd.DataFrame):
    """
    Render Product Portfolio & Category Intelligence tab.
    """
    if df.empty:
        st.warning("⚠️ No product records match the current filter selection.")
        return

    render_section_header("Strategic Portfolio Matrix (BCG Framework)", "Classifying categories by sales volume and margin efficiency")

    # BCG Matrix
    bcg_df = calculate_bcg_matrix(df, dimension="sub_category")
    if not bcg_df.empty:
        bcg_fig = plot_bcg_quadrant_matrix(bcg_df)
        st.plotly_chart(bcg_fig, use_container_width=True)

        # Quadrant Summary Pills
        stars = bcg_df[bcg_df["quadrant"].str.startswith("Stars")]["sub_category"].tolist()
        cows = bcg_df[bcg_df["quadrant"].str.startswith("Cash Cows")]["sub_category"].tolist()
        opps = bcg_df[bcg_df["quadrant"].str.startswith("Opportunities")]["sub_category"].tolist()
        under = bcg_df[bcg_df["quadrant"].str.startswith("Underperformers")]["sub_category"].tolist()

        q_col1, q_col2, q_col3, q_col4 = st.columns(4)
        with q_col1:
            st.success(f"**⭐ Stars ({len(stars)})**\n\n" + ", ".join(stars[:4]))
        with q_col2:
            st.info(f"**🐄 Cash Cows ({len(cows)})**\n\n" + ", ".join(cows[:4]))
        with q_col3:
            st.warning(f"**🚀 Opportunities ({len(opps)})**\n\n" + ", ".join(opps[:4]))
        with q_col4:
            st.error(f"**⚠️ Underperformers ({len(under)})**\n\n" + ", ".join(under[:4]))

    # Sub-Category Margin Health
    render_section_header("Sub-Category Volume & Profitability Breakdown", "Highlighting margin-dilutive vs margin-accretive lines")
    sub_fig = plot_subcategory_margin_bar(df)
    st.plotly_chart(sub_fig, use_container_width=True)

    # Pareto 80/20 Analysis
    render_section_header("Pareto 80/20 SKU Revenue Concentration", "Identifying key revenue-driving products vs long-tail catalogue")
    pareto_df, pareto_summary = calculate_pareto(df, dimension="product_name", metric="sales")

    if not pareto_df.empty:
        p_col1, p_col2, p_col3 = st.columns(3)
        with p_col1:
            st.metric("Top 20% SKU Revenue Share", f"{pareto_summary['top_20_share']:.1f}%", help="Share of total revenue generated by the top 20% of products")
        with p_col2:
            st.metric("SKUs Generating 80% Revenue", f"{pareto_summary['entities_for_80_pct']:,} / {pareto_summary['total_entities']:,}", help="Count of SKUs needed to achieve 80% of total revenue")
        with p_col3:
            st.metric("% SKUs for 80% Sales", f"{pareto_summary['pct_entities_for_80']:.1f}%", help="Percentage of total catalogue driving 80% of revenue")

        top_n = st.slider("Select Top N Products to Display in Pareto Chart:", min_value=10, max_value=50, value=25, step=5)
        pareto_fig = plot_pareto_chart(pareto_df, pareto_summary, top_n=top_n)
        st.plotly_chart(pareto_fig, use_container_width=True)

    # Top vs Bottom SKU Profitability
    render_section_header("SKU Profit Extremes: Top Performers vs Margin Drains", "Identifying the top 10 value creators and value destroyers")
    prod_agg = df.groupby(["product_name", "category", "sub_category"]).agg(
        sales=("sales", "sum"),
        profit=("profit", "sum"),
        quantity=("quantity", "sum")
    ).reset_index()

    prod_agg["profit_margin"] = (prod_agg["profit"] / prod_agg["sales"] * 100).fillna(0.0)

    top_prods = prod_agg.sort_values(by="profit", ascending=False).head(10)
    bottom_prods = prod_agg.sort_values(by="profit", ascending=True).head(10)

    t_col1, t_col2 = st.columns(2)
    with t_col1:
        st.markdown("#### 🏆 Top 10 Most Profitable SKUs")
        st.dataframe(
            top_prods[["product_name", "sub_category", "sales", "profit", "profit_margin"]].rename(columns={
                "product_name": "Product",
                "sub_category": "Sub-Category",
                "sales": "Sales ($)",
                "profit": "Profit ($)",
                "profit_margin": "Margin (%)"
            }),
            column_config={
                "Sales ($)": st.column_config.NumberColumn(format="$%.2f"),
                "Profit ($)": st.column_config.NumberColumn(format="$%.2f"),
                "Margin (%)": st.column_config.NumberColumn(format="%.1f%%")
            },
            hide_index=True,
            use_container_width=True
        )

    with t_col2:
        st.markdown("#### 🔻 Top 10 Loss-Making SKUs")
        st.dataframe(
            bottom_prods[["product_name", "sub_category", "sales", "profit", "profit_margin"]].rename(columns={
                "product_name": "Product",
                "sub_category": "Sub-Category",
                "sales": "Sales ($)",
                "profit": "Profit ($)",
                "profit_margin": "Margin (%)"
            }),
            column_config={
                "Sales ($)": st.column_config.NumberColumn(format="$%.2f"),
                "Profit ($)": st.column_config.NumberColumn(format="$%.2f"),
                "Margin (%)": st.column_config.NumberColumn(format="%.1f%%")
            },
            hide_index=True,
            use_container_width=True
        )

    render_insight_box(
        "Tables and Bookcases sub-categories contain multiple SKUs suffering deep negative margins due to excessive discounts. Strategic actions: Review supplier pricing, impose minimum margin floors on enterprise discounting, or consider SKU rationalization.",
        alert_type="info",
        title="Merchandising Action Plan"
    )
